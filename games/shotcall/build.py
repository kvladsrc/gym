"""Build the Cloudflare Pages site of Shot Call (formerly «Сколько отзывов?», English by default).

  just shotcall build

The game is page.src.html; this script puts the shot data and the base version into it and writes
  public/          the static site (index.html, shots/ as hard links, faces, fonts)
  lib/key.js       the server's answer key (true class, model class x100, genre group) + IP salt
from data/ (make.py), art/ and fonts/."""

import json
import os
import re
import secrets
import shutil
from pathlib import Path

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "data")
PUB = os.path.join(HERE, "public")

KEY = json.loads(Path(DATA, "key.json").read_text())
picks = KEY["picks"]
VERSION = KEY.get("version", 1)  # shot base; answers for another base are refused
MIN_GAP = int(
    re.search(r"const GAP = (\d+);", Path(HERE, "page.src.html").read_text()).group(1)
)
data = Path(DATA, "data.json").read_text().strip()
shots = json.loads(data)["shots"]
assert [s["id"] for s in shots] == [p["id"] for p in picks]

# ---- server key ----
groups = sorted({p["pg"] for p in picks if p["pg"] != "Other"})
T = [p["true_class"] for p in picks]
E = [round(p["model_class"] * 100) for p in picks]
G = [groups.index(p["pg"]) if p["pg"] in groups else -1 for p in picks]
os.makedirs(os.path.join(HERE, "lib"), exist_ok=True)
key_js = os.path.join(HERE, "lib", "key.js")
salt = None
if os.path.exists(key_js):
    m = re.search(r'SALT = "([0-9a-f]+)"', Path(key_js).read_text())
    salt = m and m.group(1)
salt = salt or secrets.token_hex(16)
with open(key_js, "w") as f:
    f.write("// generated by build.py from key.json; never served to players\n")
    f.write(f"export const T = {json.dumps(T, separators=(',', ':'))};\n")
    f.write(f"export const E = {json.dumps(E, separators=(',', ':'))};\n")
    f.write(f"export const G = {json.dumps(G, separators=(',', ':'))};\n")
    f.write(f'export const SALT = "{salt}";\n')
    f.write(f"export const V = {VERSION};\n")
    f.write(
        f"export const MIN_GAP = {MIN_GAP};  // classes apart for a pair to count (2 still accepted)\n"
    )

# ---- page ----
page = Path(HERE, "page.src.html").read_text()
assert page.count("__DATA__") == 1 and page.count("__V__") == 1
page = page.replace("__DATA__", data.replace("<", "\\u003c")).replace(
    "__V__", str(VERSION)
)

# ---- static files ----
os.makedirs(PUB, exist_ok=True)
Path(PUB, "index.html").write_text(page)
for f in ("face_you.png", "face_bot.png"):
    shutil.copy2(os.path.join(HERE, "art", f), os.path.join(PUB, f))
shutil.copytree(
    os.path.join(HERE, "fonts"),
    os.path.join(PUB, "fonts"),
    dirs_exist_ok=True,
    ignore=shutil.ignore_patterns("*.txt"),
)
os.makedirs(os.path.join(PUB, "shots"), exist_ok=True)
current = {sh["id"] + ".jpg" for sh in shots}
for f in os.listdir(os.path.join(PUB, "shots")):
    if f not in current:
        os.remove(os.path.join(PUB, "shots", f))
for sh in shots:
    src, dst = (
        os.path.join(DATA, "shots", sh["id"] + ".jpg"),
        os.path.join(PUB, "shots", sh["id"] + ".jpg"),
    )
    if os.path.exists(dst):
        os.remove(dst)
    os.link(src, dst)
Path(PUB, "_headers").write_text(
    "/shots/*\n  Cache-Control: public, max-age=86400\n/fonts/*\n  Cache-Control: public, max-age=604800\n"
)
print("public/index.html", len(page), "bytes;", len(shots), "shots; groups", groups)
