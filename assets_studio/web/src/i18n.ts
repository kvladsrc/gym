export type Language = "ru" | "en";

const KEY = "assets-studio.language";
const DICTIONARIES: Record<Language, Record<Key, string>> = { en, ru };

function initial(): Language {
  try {
    const stored = localStorage.getItem(KEY);
    if (stored === "ru" || stored === "en") return stored;
  } catch {
    // Storage blocked: the browser's language.
  }
  return navigator.language.toLowerCase().startsWith("ru") ? "ru" : "en";
}

export const language = signal<Language>(initial());
showLanguage(language.value);

/** The page's language and title follow the interface's. */
function showLanguage(value: Language) {
  document.documentElement.lang = value;
  document.title = DICTIONARIES[value]["app.title"];
}

export function setLanguage(next: Language) {
  language.value = next;
  showLanguage(next);
  try {
    localStorage.setItem(KEY, next);
  } catch {
    // Storage blocked: the choice lasts until the page is reloaded.
  }
}

/** Whether a key exists: for names that come from data (tasks, kinds). */
export const has = (key: string): key is Key => key in en;

/** The text for a key in the current language, with {name} filled in. */
export function t(key: Key, values: Record<string, string | number> = {}) {
  const text = DICTIONARIES[language.value][key];
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}

/** A text from a model server in the current language: its label for the
 * language if it has one (ADR-005), otherwise its own (English) text. */
export function localized(
  labels: Record<string, string> | null | undefined,
  fallback: string,
) {
  return labels?.[language.value] ?? fallback;
}
